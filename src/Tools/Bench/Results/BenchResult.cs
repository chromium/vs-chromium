using System.Text.Json;
using System.Text.Json.Serialization;
using VsChromium.Bench.Inventory;

namespace VsChromium.Bench.Results;

/// <summary>
/// The result file of a run (results/&lt;machine&gt;-&lt;disk&gt;-&lt;corpus&gt;-&lt;timestamp&gt;.json): the machine it
/// comes from, the options, and every measurement.
/// </summary>
public sealed record BenchResult {
  public int SchemaVersion { get; init; } = 1;
  public string Tool { get; init; } = "vschromium-bench";
  public string ToolVersion { get; init; } = "";
  public DateTime StartedUtc { get; init; }
  public DateTime EndedUtc { get; init; }
  public string Label { get; init; } = "";
  public MachineInfo Machine { get; init; } = new();
  public DiskInfo? Disk { get; init; }
  public SecurityInfo Security { get; init; } = new();
  public CorpusInfo Corpus { get; init; } = new();
  public ServerInfo Server { get; init; } = new();
  public RunInfo Run { get; init; } = new();
  public List<ScenarioResult> Scenarios { get; init; } = [];

  public string ToJson() => JsonSerializer.Serialize(this, ResultsJsonContext.Default.BenchResult);

  public static BenchResult FromJson(string json) =>
    JsonSerializer.Deserialize(json, ResultsJsonContext.Default.BenchResult) ?? throw new JsonException("Empty result file");
}

public sealed record CorpusInfo {
  public string Name { get; init; } = "";
  public string Path { get; init; } = "";
  public int GeneratorVersion { get; init; }
  public int FileCount { get; init; }
  public int DirectoryCount { get; init; }
  public long TotalBytes { get; init; }
  public int SearchableFileCount { get; init; }
  public int SymlinkFileCount { get; init; }
  public int SymlinkDirectoryCount { get; init; }
  /// <summary>"none", "created", or "skipped (reason)".</summary>
  public string Symlinks { get; init; } = "none";
  /// <summary>Generation time, if generated by this run (a write speed test), null if reused.</summary>
  public double? GenerationSeconds { get; init; }
}

public sealed record ServerInfo {
  /// <summary>How the server was found: path, repo, vscode, release:&lt;tag&gt;.</summary>
  public string Source { get; init; } = "";
  public string Path { get; init; } = "";
  public string Version { get; init; } = "";
  public int ProtocolVersion { get; init; }
  public string Runtime { get; init; } = "";
  /// <summary>The bench options supported by the server (e.g. "--threads"), see ServerCapabilities.</summary>
  public List<string> Capabilities { get; init; } = [];
}

public sealed record RunInfo {
  public List<string> Scenarios { get; init; } = [];
  public int Repeat { get; init; }
  /// <summary>"warm" or "cold".</summary>
  public string CacheMode { get; init; } = "warm";
  /// <summary>Why the run is warm only, if cold was asked but the cache couldn't be flushed.</summary>
  public string? CacheNote { get; init; }
  public List<int> ChangeCounts { get; init; } = [];
  public bool KeepServer { get; init; }
  /// <summary>The non-interactive command line of this run.</summary>
  public List<string> Arguments { get; init; } = [];
}

/// <summary>The measurements of a scenario.</summary>
public sealed record ScenarioResult {
  public string Name { get; init; } = "";
  public List<Metric> Metrics { get; init; } = [];
  /// <summary>Non-numeric facts (e.g. "verification method": "changeJournal").</summary>
  public Dictionary<string, string> Info { get; init; } = [];
  public List<string> Notes { get; init; } = [];
  public string? Error { get; init; }
  public bool Skipped { get; init; }
}

/// <summary>A measurement repeated <c>Values.Count</c> times.</summary>
public sealed record Metric {
  public string Name { get; init; } = "";
  /// <summary>"s", "ms", "us", "bytes", "count", "files/s".</summary>
  public string Unit { get; init; } = "";
  public List<double> Values { get; init; } = [];
  public double Median { get; init; }
  public double Min { get; init; }
  public double Max { get; init; }

  public static Metric Of(string name, string unit, IReadOnlyList<double> values) => new() {
    Name = name,
    Unit = unit,
    Values = values.ToList(),
    Median = Statistics.Median(values),
    Min = values.Count > 0 ? values.Min() : 0,
    Max = values.Count > 0 ? values.Max() : 0,
  };
}

/// <summary>Collects the values of the metrics of a scenario over the repeats.</summary>
public sealed class MetricSet {
  private readonly List<(string Name, string Unit, List<double> Values)> _metrics = [];

  public void Add(string name, string unit, double value) {
    var index = _metrics.FindIndex(m => m.Name == name);
    if (index < 0) {
      _metrics.Add((name, unit, [value]));
    } else {
      _metrics[index].Values.Add(value);
    }
  }

  public List<Metric> ToMetrics() => _metrics.Select(m => Metric.Of(m.Name, m.Unit, m.Values)).ToList();
}

public static class Statistics {
  public static double Median(IReadOnlyList<double> values) {
    if (values.Count == 0) {
      return 0;
    }
    var sorted = values.OrderBy(v => v).ToList();
    var middle = sorted.Count / 2;
    return sorted.Count % 2 == 1 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2;
  }

  public static double Percentile(IReadOnlyList<double> values, double percentile) {
    if (values.Count == 0) {
      return 0;
    }
    var sorted = values.OrderBy(v => v).ToList();
    var index = (int)Math.Ceiling(percentile / 100.0 * sorted.Count) - 1;
    return sorted[Math.Clamp(index, 0, sorted.Count - 1)];
  }
}

