using VsChromium.ProtocolGen.Model;

namespace VsChromium.ProtocolGen.Emitters;

/// <summary>
/// Generates the client side code of the protocol for the Visual Studio extension (C# 7.3, .NET
/// Framework, Newtonsoft.Json and StreamJsonRpc):
/// <list type="bullet">
/// <item>The models (classes) and enums, serialized with Newtonsoft.Json.</item>
/// <item><c>ProtocolMethods</c>: the method names.</item>
/// <item><c>ProtocolClient</c>: one method per request, wrapping a <c>StreamJsonRpc.JsonRpc</c>
/// (parameters sent as a single object: JSON-RPC named parameters).</item>
/// <item><c>IProtocolNotifications</c>: one method per notification, implemented by the client and
/// registered with <c>JsonRpc.AddLocalRpcTarget</c>.</item>
/// </list>
/// </summary>
public static class CSharpClientEmitter {
  public static string Emit(ProtocolDefinition protocol) {
    var w = new CodeWriter();
    w.Line("// <auto-generated>");
    w.Line("// Generated by src/Tools/ProtocolGen from the protocol definition (protocol/*.tsp).");
    w.Line("// Do not edit: changes are overwritten by the next generation.");
    w.Line("// </auto-generated>");
    w.Line();
    w.Line("using System;");
    w.Line("using System.Collections.Generic;");
    w.Line("using System.Runtime.Serialization;");
    w.Line("using System.Threading;");
    w.Line("using System.Threading.Tasks;");
    w.Line("using Newtonsoft.Json;");
    w.Line("using Newtonsoft.Json.Converters;");
    w.Line("using StreamJsonRpc;");
    w.Line();
    w.Open($"namespace {CSharpServerEmitter.Namespace(protocol)}");

    foreach (var protocolEnum in protocol.Enums) {
      EmitEnum(w, protocolEnum);
      w.Line();
    }
    foreach (var model in protocol.Models) {
      EmitModel(w, model);
      w.Line();
    }

    EmitMethodNames(w, protocol);
    w.Line();
    EmitClient(w, protocol);
    w.Line();
    EmitNotifications(w, protocol);

    w.Close();
    return w.ToString();
  }

  private static void EmitEnum(CodeWriter w, ProtocolEnum protocolEnum) {
    w.CSharpDoc(protocolEnum.Doc);
    w.Line("[JsonConverter(typeof(StringEnumConverter))]");
    w.Open($"public enum {protocolEnum.Name}");
    foreach (var member in protocolEnum.Members) {
      w.CSharpDoc(member.Doc);
      w.Line($"[EnumMember(Value = \"{member.Value}\")]");
      w.Line($"{Naming.Pascal(member.Name)},");
    }
    w.Close();
  }

  private static void EmitModel(CodeWriter w, ProtocolModel model) {
    w.CSharpDoc(model.Doc ?? (model.IsSynthesized ? "Parameters of an operation (generated from its inline parameters)." : null));
    w.Open($"public sealed partial class {model.Name}");
    var first = true;
    foreach (var field in model.Fields) {
      if (!first)
        w.Line();
      first = false;
      w.CSharpDoc(field.Doc);
      w.Line(field.IsOptional
        ? $"[JsonProperty(\"{field.Name}\", NullValueHandling = NullValueHandling.Ignore)]"
        : $"[JsonProperty(\"{field.Name}\")]");
      var initializer = field.Type.IsArray ? $" = new {CSharpServerEmitter.CSharpType(field)}();" : "";
      w.Line($"public {CSharpType(field)} {Naming.Pascal(field.Name)} {{ get; set; }}{initializer}");
    }
    w.Close();
  }

  /// <summary>The C# type of a field (no nullable reference types in C# 7.3).</summary>
  private static string CSharpType(ProtocolField field) {
    var type = CSharpServerEmitter.CSharpType(field);
    if (field.IsOptional && !field.Type.IsArray && (field.Type.Scalar == ScalarKind.String || field.Type.Model != null))
      return type.TrimEnd('?');
    return type;
  }

  private static string MethodDoc(ProtocolMethod method) =>
    $"\"{method.Name}\"" + (method.Doc == null ? "" : ": " + method.Doc);

  private static void EmitMethodNames(CodeWriter w, ProtocolDefinition protocol) {
    w.CSharpDoc("The names of the methods of the protocol (JSON-RPC \"method\").");
    w.Open("public static class ProtocolMethods");
    foreach (var method in protocol.Methods) {
      w.Line($"public const string {method.Identifier} = \"{method.Name}\";");
    }
    w.Close();
  }

  private static void EmitClient(CodeWriter w, ProtocolDefinition protocol) {
    w.CSharpDoc(
      "The requests of the protocol (client to server), sent with a <see cref=\"JsonRpc\"/>. The\n" +
      "parameters are sent as a single object (JSON-RPC named parameters).", escape: false);
    w.Open("public sealed partial class ProtocolClient");
    w.Line("private readonly JsonRpc _rpc;");
    w.Line();
    w.Open("public ProtocolClient(JsonRpc rpc)");
    w.Line("_rpc = rpc ?? throw new ArgumentNullException(nameof(rpc));");
    w.Close();
    w.Line();
    w.CSharpDoc("The JSON-RPC connection.");
    w.Line("public JsonRpc Rpc => _rpc;");
    foreach (var method in protocol.Requests) {
      w.Line();
      w.CSharpDoc(MethodDoc(method));
      var result = method.Result == null ? "Task" : $"Task<{method.Result.Name}>";
      var parameters = method.Parameters == null ? "" : $"{method.Parameters.Name} parameters, ";
      var argument = method.Parameters == null ? "null" : "parameters";
      var invoke = method.Result == null ? "InvokeWithParameterObjectAsync" : $"InvokeWithParameterObjectAsync<{method.Result.Name}>";
      w.Line($"public {result} {method.Identifier}Async({parameters}CancellationToken cancellationToken = default(CancellationToken)) =>");
      w.Line($"  _rpc.{invoke}(ProtocolMethods.{method.Identifier}, {argument}, cancellationToken);");
    }
    w.Close();
  }

  private static void EmitNotifications(CodeWriter w, ProtocolDefinition protocol) {
    w.CSharpDoc(
      "The notifications of the protocol (server to client), implemented by the client and registered\n" +
      "with <c>JsonRpc.AddLocalRpcTarget&lt;IProtocolNotifications&gt;(target, null)</c>.", escape: false);
    w.Open("public interface IProtocolNotifications");
    var first = true;
    foreach (var method in protocol.Notifications) {
      if (!first)
        w.Line();
      first = false;
      w.CSharpDoc(MethodDoc(method));
      if (method.Parameters == null) {
        w.Line($"[JsonRpcMethod(ProtocolMethods.{method.Identifier})]");
        w.Line($"void {method.Identifier}();");
      } else {
        w.Line($"[JsonRpcMethod(ProtocolMethods.{method.Identifier}, UseSingleObjectParameterDeserialization = true)]");
        w.Line($"void {method.Identifier}({method.Parameters.Name} parameters);");
      }
    }
    w.Close();
  }
}
