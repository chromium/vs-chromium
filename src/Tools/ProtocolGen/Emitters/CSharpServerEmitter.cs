using VsChromium.ProtocolGen.Model;

namespace VsChromium.ProtocolGen.Emitters;

/// <summary>
/// Generates the server side code of the protocol (C#, modern .NET, NativeAOT compatible):
/// <list type="bullet">
/// <item>The models (classes) and enums, serialized with System.Text.Json.</item>
/// <item><c>ProtocolMethods</c>: the method names.</item>
/// <item><c>IProtocolRequestHandler</c>: one method per request, implemented by the server.</item>
/// <item><c>ProtocolDispatcher</c>: deserializes the parameters of a request, calls the handler and
/// serializes the result (no reflection).</item>
/// <item><c>ProtocolNotificationSender</c>: serializes the notifications sent by the server.</item>
/// <item><c>ProtocolJsonContext</c>: the System.Text.Json source generation context.</item>
/// </list>
/// </summary>
public static class CSharpServerEmitter {
  public static string Emit(ProtocolDefinition protocol) {
    var w = new CodeWriter();
    w.Line("// <auto-generated>");
    w.Line("// Generated by src/Tools/ProtocolGen from the protocol definition (protocol/*.tsp).");
    w.Line("// Do not edit: changes are overwritten by the next build.");
    w.Line("// </auto-generated>");
    w.Line();
    w.Line("#nullable enable");
    w.Line();
    w.Line("using System;");
    w.Line("using System.Collections.Generic;");
    w.Line("using System.Text.Json;");
    w.Line("using System.Text.Json.Serialization;");
    w.Line("using System.Text.Json.Serialization.Metadata;");
    w.Line("using System.Threading;");
    w.Line("using System.Threading.Tasks;");
    w.Line();
    w.Open($"namespace {protocol.Namespace}");

    foreach (var protocolEnum in protocol.Enums) {
      EmitEnum(w, protocolEnum);
      w.Line();
    }
    foreach (var model in protocol.Models) {
      EmitModel(w, model);
      w.Line();
    }

    EmitMethodNames(w, protocol);
    w.Line();
    EmitRequestHandler(w, protocol);
    w.Line();
    EmitDispatcher(w, protocol);
    w.Line();
    EmitNotificationSender(w, protocol);
    w.Line();
    EmitExceptions(w);
    w.Line();
    EmitJsonContext(w, protocol);

    w.Close();
    return w.ToString();
  }

  private static void EmitEnum(CodeWriter w, ProtocolEnum protocolEnum) {
    w.CSharpDoc(protocolEnum.Doc);
    w.Line($"[JsonConverter(typeof(JsonStringEnumConverter<{protocolEnum.Name}>))]");
    w.Open($"public enum {protocolEnum.Name}");
    foreach (var member in protocolEnum.Members) {
      w.CSharpDoc(member.Doc);
      w.Line($"[JsonStringEnumMemberName(\"{member.Value}\")]");
      w.Line($"{Naming.Pascal(member.Name)},");
    }
    w.Close();
  }

  private static void EmitModel(CodeWriter w, ProtocolModel model) {
    w.CSharpDoc(model.Doc ?? (model.IsSynthesized ? "Parameters of an operation (generated from its inline parameters)." : null));
    w.Open($"public sealed partial class {model.Name}");
    var first = true;
    foreach (var field in model.Fields) {
      if (!first)
        w.Line();
      first = false;
      w.CSharpDoc(field.Doc);
      w.Line($"[JsonPropertyName(\"{field.Name}\")]");
      if (field.IsOptional)
        w.Line("[JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]");
      w.Line($"public {CSharpType(field)} {Naming.Pascal(field.Name)} {{ get; set; }}{Initializer(field)}");
    }
    w.Close();
  }

  public static string CSharpType(ProtocolField field) {
    var element = field.Type.Scalar switch {
      ScalarKind.String => "string",
      ScalarKind.Boolean => "bool",
      ScalarKind.Int32 => "int",
      ScalarKind.Int64 => "long",
      ScalarKind.Float64 => "double",
      ScalarKind.UtcDateTime => "DateTime",
      null => field.Type.Model?.Name ?? field.Type.Enum!.Name,
      _ => throw new InvalidOperationException(),
    };
    if (field.Type.IsArray)
      return $"List<{element}>";
    return field.IsOptional ? element + "?" : element;
  }

  private static string Initializer(ProtocolField field) {
    if (field.IsOptional)
      return "";
    if (field.Type.IsArray)
      return " = new();";
    if (field.Type.Scalar == ScalarKind.String)
      return " = \"\";";
    if (field.Type.Model != null)
      return " = null!;";
    return "";
  }

  private static void EmitMethodNames(CodeWriter w, ProtocolDefinition protocol) {
    w.CSharpDoc("The names of the methods of the protocol (JSON-RPC \"method\").");
    w.Open("public static class ProtocolMethods");
    foreach (var method in protocol.Methods) {
      w.Line($"public const string {method.Identifier} = \"{method.Name}\";");
    }
    w.Close();
  }

  private static string HandlerSignature(ProtocolMethod method) {
    var result = method.Result == null ? "ValueTask" : $"ValueTask<{method.Result.Name}>";
    var parameters = method.Parameters == null
      ? "CancellationToken cancellationToken"
      : $"{method.Parameters.Name} parameters, CancellationToken cancellationToken";
    return $"{result} {method.Identifier}Async({parameters})";
  }

  private static void EmitRequestHandler(CodeWriter w, ProtocolDefinition protocol) {
    w.CSharpDoc("The requests of the protocol, implemented by the server.");
    w.Open("public interface IProtocolRequestHandler");
    var first = true;
    foreach (var method in protocol.Requests) {
      if (!first)
        w.Line();
      first = false;
      w.CSharpDoc($"\"{method.Name}\"" + (method.Doc == null ? "" : ": " + method.Doc));
      w.Line(HandlerSignature(method) + ";");
    }
    w.Close();
  }

  private static void EmitDispatcher(CodeWriter w, ProtocolDefinition protocol) {
    w.CSharpDoc("Dispatches the requests of the protocol to an <see cref=\"IProtocolRequestHandler\"/>.", escape: false);
    w.Open("public static class ProtocolDispatcher");
    w.CSharpDoc("True if <paramref name=\"method\"/> is a request of the protocol.", escape: false);
    w.Line("public static bool IsRequest(string method) => method switch {");
    foreach (var method in protocol.Requests) {
      w.Line($"  ProtocolMethods.{method.Identifier} => true,");
    }
    w.Line("  _ => false,");
    w.Line("};");
    w.Line();
    w.CSharpDoc(
      "Deserializes the parameters of the request <paramref name=\"method\"/>, calls the handler, and\n" +
      "returns the serialized result (null for requests without result). Throws <see\n" +
      "cref=\"ProtocolMethodNotFoundException\"/> for unknown methods, <see\n" +
      "cref=\"ProtocolInvalidParamsException\"/> for invalid parameters.", escape: false);
    w.Open("public static async ValueTask<JsonElement?> DispatchRequestAsync(IProtocolRequestHandler handler, string method, JsonElement? parameters, CancellationToken cancellationToken)");
    w.Open("switch (method)");
    foreach (var method in protocol.Requests) {
      w.Open($"case ProtocolMethods.{method.Identifier}:");
      var call = method.Parameters == null
        ? $"handler.{method.Identifier}Async(cancellationToken)"
        : $"handler.{method.Identifier}Async(DeserializeParameters(parameters, ProtocolJsonContext.Default.{method.Parameters.Name}), cancellationToken)";
      if (method.Result == null) {
        w.Line($"await {call}.ConfigureAwait(false);");
        w.Line("return null;");
      } else {
        w.Line($"var result = await {call}.ConfigureAwait(false);");
        w.Line($"return JsonSerializer.SerializeToElement(result, ProtocolJsonContext.Default.{method.Result.Name});");
      }
      w.Close();
    }
    w.Line("default:");
    w.Line("  throw new ProtocolMethodNotFoundException(method);");
    w.Close();
    w.Close();
    w.Line();
    w.Open("private static T DeserializeParameters<T>(JsonElement? parameters, JsonTypeInfo<T> typeInfo)");
    w.Open("if (parameters is not { ValueKind: JsonValueKind.Object } value)");
    w.Line("throw new ProtocolInvalidParamsException(\"The parameters must be an object\");");
    w.Close();
    w.Open("try");
    w.Line("return value.Deserialize(typeInfo) ?? throw new ProtocolInvalidParamsException(\"Missing parameters\");");
    w.Close();
    w.Open("catch (JsonException e)");
    w.Line("throw new ProtocolInvalidParamsException(e.Message, e);");
    w.Close();
    w.Close();
    w.Close();
  }

  private static void EmitNotificationSender(CodeWriter w, ProtocolDefinition protocol) {
    w.CSharpDoc("Sends the notifications of the protocol (server to client): serializes their parameters.");
    w.Open("public abstract class ProtocolNotificationSender");
    w.Line("protected abstract void SendNotification(string method, JsonElement? parameters);");
    foreach (var method in protocol.Notifications) {
      w.Line();
      w.CSharpDoc($"\"{method.Name}\"" + (method.Doc == null ? "" : ": " + method.Doc));
      if (method.Parameters == null) {
        w.Line($"public void {method.Identifier}() => SendNotification(ProtocolMethods.{method.Identifier}, null);");
      } else {
        w.Line($"public void {method.Identifier}({method.Parameters.Name} parameters) =>");
        w.Line($"  SendNotification(ProtocolMethods.{method.Identifier}, JsonSerializer.SerializeToElement(parameters, ProtocolJsonContext.Default.{method.Parameters.Name}));");
      }
    }
    w.Close();
  }

  private static void EmitExceptions(CodeWriter w) {
    w.CSharpDoc("An error of a request, reported to the client with a JSON-RPC error code.");
    w.Open("public class ProtocolException : Exception");
    w.Open("public ProtocolException(int code, string message, Exception? innerException = null) : base(message, innerException)");
    w.Line("Code = code;");
    w.Close();
    w.Line();
    w.CSharpDoc("The JSON-RPC error code.");
    w.Line("public int Code { get; }");
    w.Close();
    w.Line();
    w.Open("public sealed class ProtocolMethodNotFoundException : ProtocolException");
    w.Line("public const int ErrorCode = -32601;");
    w.Line();
    w.Open("public ProtocolMethodNotFoundException(string method) : base(ErrorCode, $\"Unknown method \\\"{method}\\\"\")");
    w.Line("Method = method;");
    w.Close();
    w.Line();
    w.Line("public string Method { get; }");
    w.Close();
    w.Line();
    w.Open("public sealed class ProtocolInvalidParamsException : ProtocolException");
    w.Line("public const int ErrorCode = -32602;");
    w.Line();
    w.Line("public ProtocolInvalidParamsException(string message, Exception? innerException = null) : base(ErrorCode, \"Invalid parameters: \" + message, innerException) { }");
    w.Close();
  }

  private static void EmitJsonContext(CodeWriter w, ProtocolDefinition protocol) {
    w.CSharpDoc(
      "System.Text.Json source generation context of the protocol models. Integers are also read from\n" +
      "strings (the protobuf JSON mapping writes 64 bit integers as strings).");
    w.Line("[JsonSourceGenerationOptions(");
    w.Line("  NumberHandling = JsonNumberHandling.AllowReadingFromString,");
    w.Line("  DefaultIgnoreCondition = JsonIgnoreCondition.Never)]");
    foreach (var model in protocol.Models) {
      w.Line($"[JsonSerializable(typeof({model.Name}))]");
    }
    w.Line("public partial class ProtocolJsonContext : JsonSerializerContext {");
    w.Line("}");
  }
}
