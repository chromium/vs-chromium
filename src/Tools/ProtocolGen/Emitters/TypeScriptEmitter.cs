using VsChromium.ProtocolGen.Model;

namespace VsChromium.ProtocolGen.Emitters;

/// <summary>
/// Generates the client side code of the protocol for the VS Code extension (TypeScript, npm package
/// "vscode-jsonrpc"):
/// <list type="bullet">
/// <item>The enums (string literal union types) and the models (interfaces).</item>
/// <item>One namespace per request (<c>SearchCodeRequest</c>) and per notification
/// (<c>IndexStateChangedNotification</c>) with the method name and the typed
/// <c>RequestType</c>/<c>NotificationType</c>, in the style of vscode-languageserver-protocol.</item>
/// </list>
/// </summary>
public static class TypeScriptEmitter {
  public static string Emit(ProtocolDefinition protocol) {
    var w = new CodeWriter();
    w.Line("// <auto-generated>");
    w.Line("// Generated by src/Tools/ProtocolGen from the protocol definition (protocol/*.tsp).");
    w.Line("// Do not edit: changes are overwritten by the next generation.");
    w.Line("// </auto-generated>");
    w.Line();

    var imports = new SortedSet<string>(StringComparer.Ordinal);
    foreach (var method in protocol.Methods)
      imports.Add(TypeClass(method));
    if (imports.Count > 0) {
      w.Line($"import {{ {string.Join(", ", imports)} }} from 'vscode-jsonrpc';");
      w.Line();
    }

    foreach (var protocolEnum in protocol.Enums) {
      EmitEnum(w, protocolEnum);
      w.Line();
    }
    foreach (var model in protocol.Models) {
      EmitModel(w, model);
      w.Line();
    }

    var first = true;
    foreach (var method in protocol.Methods) {
      if (!first)
        w.Line();
      first = false;
      EmitMethod(w, method);
    }
    return w.ToString();
  }

  /// <summary>Name of the namespace of a method, e.g. "SearchCodeRequest", "IndexLoadedNotification".</summary>
  public static string MethodNamespace(ProtocolMethod method) =>
    method.Identifier + (method.Kind == MethodKind.Request ? "Request" : "Notification");

  private static string TypeClass(ProtocolMethod method) {
    if (method.Kind == MethodKind.Notification)
      return method.Parameters == null ? "NotificationType0" : "NotificationType";
    return method.Parameters == null ? "RequestType0" : "RequestType";
  }

  private static void EmitEnum(CodeWriter w, ProtocolEnum protocolEnum) {
    var doc = protocolEnum.Doc ?? "";
    var members = protocolEnum.Members.Where(m => m.Doc != null).ToList();
    if (members.Count > 0) {
      if (doc.Length > 0)
        doc += "\n\n";
      doc += string.Join("\n", members.Select(m => $"- `'{m.Value}'`: " + m.Doc!.Replace("\n", "\n  ")));
    }
    w.JsDoc(doc);
    var values = string.Join(" | ", protocolEnum.Members.Select(m => $"'{m.Value}'"));
    w.Line($"export type {protocolEnum.Name} = {values};");
  }

  private static void EmitModel(CodeWriter w, ProtocolModel model) {
    w.JsDoc(model.Doc ?? (model.IsSynthesized ? "Parameters of an operation (generated from its inline parameters)." : null));
    w.Open($"export interface {model.Name}");
    foreach (var field in model.Fields) {
      w.JsDoc(field.Doc);
      w.Line($"{field.Name}{(field.IsOptional ? "?" : "")}: {TypeScriptType(field.Type)};");
    }
    w.Close();
  }

  public static string TypeScriptType(FieldType type) {
    var element = type.Scalar switch {
      ScalarKind.String => "string",
      ScalarKind.Boolean => "boolean",
      ScalarKind.Int32 or ScalarKind.Int64 or ScalarKind.Float64 => "number",
      ScalarKind.UtcDateTime => "string",
      null => type.Model?.Name ?? type.Enum!.Name,
      _ => throw new InvalidOperationException(),
    };
    return type.IsArray ? element + "[]" : element;
  }

  private static void EmitMethod(CodeWriter w, ProtocolMethod method) {
    var direction = method.Kind == MethodKind.Request ? "Request (client to server)" : "Notification (server to client)";
    w.JsDoc($"{direction} \"{method.Name}\"" + (method.Doc == null ? "." : ": " + method.Doc));
    w.Open($"export namespace {MethodNamespace(method)}");
    w.Line($"export const method = '{method.Name}';");
    var typeClass = TypeClass(method);
    var result = method.Result?.Name ?? "null";
    var typeArguments = method.Kind == MethodKind.Notification
      ? method.Parameters?.Name
      : method.Parameters == null ? $"{result}, void" : $"{method.Parameters.Name}, {result}, void";
    var generic = typeArguments == null ? "" : $"<{typeArguments}>";
    w.Line($"export const type = new {typeClass}{generic}(method);");
    w.Close();
  }
}
